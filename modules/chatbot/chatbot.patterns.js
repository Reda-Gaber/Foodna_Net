function normalizeForMatch(text) {
  return String(text || '')
    .replace(/[إأآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[^\u0600-\u06FFa-zA-Z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function hasProductKeyword(normalizedText) {
  const n = normalizedText || '';
  return PRODUCT_KEYWORDS.some((kw) => {
    const k = normalizeForMatch(kw);
    return k.length >= 2 && n.includes(k);
  });
}

function matchesAny(normalizedText, patterns) {
  return patterns.some((p) => p.test(normalizedText));
}

function isStopWord(word) {
  return STOP_WORDS.has(word) || word.length < 2;
}

